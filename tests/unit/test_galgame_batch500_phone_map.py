@pytest.mark.parametrize("reading,kana,phones", POSITIVE)
def test_observed_batch500_candidates_cover_every_mora(reading, kana, phones):
    morae = tuple(Mora(0, i, value) for i, value in enumerate(kana))
    owners = _match_morae_to_phones(morae, phones, PHONE_MAP)
    assert len(owners) == len(phones)
    assert {m.index_in_token for group in owners for m in group} == set(range(len(kana)))

@pytest.mark.parametrize("reading,kana,phones", NEGATIVE)
def test_unresolved_batch500_candidates_remain_rejected(reading, kana, phones):
    morae = tuple(Mora(0, i, value) for i, value in enumerate(kana))
    with pytest.raises(StageFailure):
        _match_morae_to_phones(morae, phones, PHONE_MAP)
